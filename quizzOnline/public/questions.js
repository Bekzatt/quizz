function parseQuestions(text){
  return String(text||'').split(/\r?\n/).map(l=>l.trim()).filter(l=>l && !l.startsWith('#'))
    .map(l=>l.split(/[|\t]/).map(s=>s.trim())).filter(p=>p.length>=3 && p.slice(0,4).every(Boolean))
    .map(p=>({q:p[0], a:p[1], w:p.slice(2,4)}));
}
